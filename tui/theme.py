from __future__ import annotations

from string import Template

PAGE_BACKGROUND = "#181818"
SURFACE_BACKGROUND = "#2a2a2a"
TEXT_PRIMARY = "#ffffff"
TEXT_MUTED = "#8b8b8b"
REFERENCE_BACKGROUND = "#4a4a4a"

PLAN_MODE = TEXT_MUTED
BUILD_MODE = TEXT_PRIMARY
APPROVE_FOR_ME = "#7bbefd"
FULL_ACCESS = "#fe8549"

INFO_BAR_BACKGROUND = "#1e1e1e"
OVERLAY_BACKGROUND = "rgba(0, 0, 0, 0.6)"

DIFF_ADD_BG = "#1e3a1e"
DIFF_ADD_FG = "#7fd97f"
DIFF_DEL_BG = "#3a1e1e"
DIFF_DEL_FG = "#d97f7f"

STATUS_INFO = APPROVE_FOR_ME
STATUS_SUCCESS = DIFF_ADD_FG
STATUS_ERROR = DIFF_DEL_FG
STATUS_WARNING = "#e6c86e"
STATUS_MUTED = TEXT_MUTED


def render_css(template: str) -> str:
    return Template(template).substitute(
        PAGE_BACKGROUND=PAGE_BACKGROUND,
        SURFACE_BACKGROUND=SURFACE_BACKGROUND,
        TEXT_PRIMARY=TEXT_PRIMARY,
        TEXT_MUTED=TEXT_MUTED,
        REFERENCE_BACKGROUND=REFERENCE_BACKGROUND,
        PLAN_MODE=PLAN_MODE,
        BUILD_MODE=BUILD_MODE,
        APPROVE_FOR_ME=APPROVE_FOR_ME,
        FULL_ACCESS=FULL_ACCESS,
        INFO_BAR_BACKGROUND=INFO_BAR_BACKGROUND,
        OVERLAY_BACKGROUND=OVERLAY_BACKGROUND,
        DIFF_ADD_BG=DIFF_ADD_BG,
        DIFF_ADD_FG=DIFF_ADD_FG,
        DIFF_DEL_BG=DIFF_DEL_BG,
        DIFF_DEL_FG=DIFF_DEL_FG,
        STATUS_INFO=STATUS_INFO,
        STATUS_SUCCESS=STATUS_SUCCESS,
        STATUS_ERROR=STATUS_ERROR,
        STATUS_WARNING=STATUS_WARNING,
        STATUS_MUTED=STATUS_MUTED,
    )
